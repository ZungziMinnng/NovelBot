"""玩法类别：模拟器 / 探索冒险 / 角色养成。

genre 决定世界是什么，play_style 决定这局怎么玩。同一个魔法学院可以是身份
模拟器、角色养成或探索冒险；玩法规则必须明确告诉模型当前的循环和反馈周期。
"""

STYLE_LABELS = {
    "sim": "模拟器",
    "rpg": "探索冒险",
    "slg": "角色养成",
}

DEFAULT_STYLE = "rpg"

STYLE_RULES = {
    "sim": """【玩法：模拟器】
这是一个身份、职业或系统模拟。玩家玩的是「如何运行这套生活或制度」，不是关卡。

- 推进靠时间和玩家安排。每个行动应该消耗一段时间，并改变系统状态。
- 重点是身份、权限、资源、日程和环境反馈，不要凭空改成线性冒险。
- 冲突来自系统约束：资源不足、权限不够、日程冲突、关系变化和外部压力。
- 数值变化要写成生活或制度后果，不要只报数字。
- 世界会按自己的规则继续运行，玩家不操作时也可以发生有限的背景变化。""",
    "rpg": """【玩法：探索冒险】
这是一场冒险。玩家玩的是「去看看那边有什么」。

- 每个地点都该有东西可看。写地点先写感官：光线、气味、声音、哪里不对劲。
- 道具和线索是硬通货。玩家捡到的东西后面要能用上，别发一堆装饰品。
- 危险要提前露出来。门后有怪，先让他听见声音；不能开门就死。
- 玩家做了有风险的事，结果要落到实处——受伤、丢东西、惊动了谁。
- 不要替玩家决定他要去哪。给出路，让他挑。""",
    "slg": """【玩法：角色养成】
这是一套日式角色养成模拟。玩家玩的是「今天如何安排目标角色，以及关系会走到哪一步」。

- 以一天或一组行动为基本循环：安排指令、执行行动、推进时间，再检查事件。
- 目标角色的属性、关系和阶段变化必须有连续性，不能每轮重置成一次性剧情。
- 行动要有成本和反馈：消耗时间、精力或其他已有数值，并影响后续选择。
- 阈值和条件用于解锁事件、改变互动方式和推动分支结局；不要只写即时对话。
- 角色仍然有自己的反应和边界，玩家做选择，模型负责把状态变化演出来。""",
}


def style_label(play_style: str | None) -> str:
    """给界面用的中文名。未知值一律按默认类别算。"""
    return STYLE_LABELS.get((play_style or "").strip() or DEFAULT_STYLE, STYLE_LABELS[DEFAULT_STYLE])


def style_block(play_style: str | None) -> str:
    """拼进 system 的玩法规则；旧库或脏数据回落到探索冒险。"""
    key = (play_style or "").strip() or DEFAULT_STYLE
    return STYLE_RULES.get(key, STYLE_RULES[DEFAULT_STYLE])
