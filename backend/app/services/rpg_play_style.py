"""玩法类别：模拟 / 探索冒险 / 经营策略。

和 genre（题材）是两根正交的轴。genre 说「世界长什么样」——魔法学院、现代都市；
play_style 说「这局怎么玩」——同一个魔法学院，可以是每天上课攒好感的模拟养成，
也可以是钻地下城的探索冒险。模型拿不到后者的时候，它只能按题材去猜节奏，
于是模拟养成里凭空冒出打斗，经营策略里一回合只推进十分钟。

规则文字写成常量而不是模板文件：一共三段、每段十来行，`genre_cards` 那套
目录加别名匹配是为十三张卡准备的，三段话套上去只会多两层间接。

注入方式是**独立的一段**，不进 rpg_gm.jinja2。那个模板用户能在
「提示词设置」里改，改过的人存的是旧版本；往模板里加占位符，对他们就是
静默失效——玩法类别选了没反应，还查不出为什么。
"""

STYLE_LABELS = {
    "sim": "模拟",
    "rpg": "探索冒险",
    "slg": "经营策略",
}

DEFAULT_STYLE = "rpg"

STYLE_RULES = {
    "sim": """【玩法：模拟】
这是一个生活模拟。玩家玩的是「日子」，不是「关卡」。

- 推进靠时间，不靠事件。一轮就是做一件事的工夫，做完了就该往前走一点。
- 别自己制造危机。没有反派在追他，也没有倒计时。冲突来自钱不够、
  精力不够、两个人同时约了他这种事。
- 数值就是日子的质量。精力见底要写成累，钱见底要写成买不起，
  不要只报数字。
- 人是主角。同一个人反复出现、慢慢变熟，比来一个新角色有意思得多。
- 不要写打斗。真起了冲突也是吵架、冷战、撂脸子。""",
    "rpg": """【玩法：探索冒险】
这是一场冒险。玩家玩的是「去看看那边有什么」。

- 每个地点都该有东西可看。写地点先写感官：光线、气味、声音、哪里不对劲。
- 道具和线索是硬通货。玩家捡到的东西后面要能用上，别发一堆装饰品。
- 危险要提前露出来。门后有怪，先让他听见声音；不能开门就死。
- 玩家做了有风险的事，结果要落到实处——受伤、丢东西、惊动了谁。
- 不要替玩家决定他要去哪。给出路，让他挑。""",
    "slg": """【玩法：经营策略】
这是一盘经营。玩家玩的是「这一步资源花在哪」。

- 一轮的尺度是一个周期（一旬、一月、一季），不是一个瞬间。写的是这段时间
  里发生了什么，不是一句对话。
- 每一步都要有代价。给他好处的同时说清楚少了什么、谁不高兴了。
- 数字要摆出来。产出多少、耗掉多少、还剩多少，含糊其辞玩家就没法决策。
- 局势会自己动。他不出手，别人也在扩张、在涨价、在结盟。
- 收尾留一个决策口子：接下来摆在他面前的是哪几条路，各自要付什么。""",
}


def style_label(play_style: str | None) -> str:
    """给界面用的中文名。未知值一律按默认类别算。"""
    return STYLE_LABELS.get((play_style or "").strip() or DEFAULT_STYLE, STYLE_LABELS[DEFAULT_STYLE])


def style_block(play_style: str | None) -> str:
    """拼进 system 的那一段玩法规则。

    未知值（老库的空串、手改过库的脏数据）回落到默认类别，而默认类别的规则
    就是照着现在这套 GM 提示词写的，所以老模组读出来行为不变。
    """
    key = (play_style or "").strip() or DEFAULT_STYLE
    return STYLE_RULES.get(key, STYLE_RULES[DEFAULT_STYLE])
